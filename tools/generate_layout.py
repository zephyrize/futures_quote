#!/usr/bin/env python3
"""Generate structural validation from the pinned CME schema (no field decoding)."""
import hashlib
import pathlib
import xml.etree.ElementTree as ET

root = pathlib.Path(__file__).resolve().parents[1]
schema = root / "schemas/cme/templates_v13.xml"
xml = ET.parse(schema).getroot()
types = {t.attrib["name"]: t for t in xml.find("types")}
sizes = {"char": 1, "uint8": 1, "int8": 1, "uint16": 2, "int16": 2,
         "uint32": 4, "int32": 4, "uint64": 8, "int64": 8}

def group_code(g, indent):
    dim = types[g.attrib["dimensionType"]]
    offset = 0
    for field in dim:
        start = int(field.attrib.get("offset", offset))
        size = sizes[field.attrib["primitiveType"]]
        if field.attrib["name"] == "numInGroup":
            count_offset, count_size = start, size
        offset = start + size
    minimum = int(g.attrib["blockLength"])
    lines = ["{", f"b.require(pos, {offset});", "size_t block=b.u16(pos);",
             f"size_t count=b.u{count_size * 8}(pos+{count_offset});",
             f'if(block<{minimum}) throw ParseError("short CME group block");',
             f"pos+={offset};", "if(count && block>(b.n-pos)/count) throw ParseError(\"CME group exceeds message\");"]
    children = list(g.findall("group"))
    if children:
        lines += ["for(size_t i=0;i<count;++i) { pos+=block;"]
        for child in children:
            lines += group_code(child, 0)
        lines += ["}"]
    else:
        lines += ["pos+=block*count;"]
    lines += ["}"]
    return [" " * indent + line for line in lines]

lines = ["// Generated by tools/generate_layout.py. Do not edit.",
         "// schema SHA256: " + hashlib.sha256(schema.read_bytes()).hexdigest(),
         "#ifndef FQ_CME_LAYOUT_HPP", "#define FQ_CME_LAYOUT_HPP",
         '#include "bytes.hpp"', "namespace fqimpl {",
         "inline bool validate_cme_message(Bytes b) {",
         "b.require(0,10);",
         'if(b.u16(0)!=b.n || b.u16(6)!=1 || b.u16(8)!=13) throw ParseError("unsupported CME size/schema/version");',
         "size_t root=b.u16(2); b.require(10,root); size_t pos=10+root;",
         "switch(b.u16(4)) {"]
manifest = []
for m in xml:
    if m.tag.split("}")[-1] != "message":
        continue
    assert not list(m.iter("data")), "variable data needs an explicit validator"
    template, block = int(m.attrib["id"]), int(m.attrib["blockLength"])
    lines += [f"case {template}: {{", f'if(root<{block}) throw ParseError("short CME root block");']
    for g in m.findall("group"):
        lines += group_code(g, 0)
    lines += ["break; }"]
    manifest.append(f"| {template} | {m.attrib['name']} | {block} |")
lines += ["default: return false;", "}",
          'if(pos!=b.n) throw ParseError("CME message has trailing/missing bytes");',
          "return true; }", "}", "#endif"]
(root / "generated/cme/cme_layout.hpp").write_text("\n".join(lines)+"\n")
(root / "docs/cme-templates.md").write_text(
    "CME v13 结构校验覆盖表（不等同于全部业务语义支持，详见 protocol-support.md）。\n\n"
    "| ID | Message | Root bytes |\n|---|---|---|\n"+"\n".join(manifest)+"\n")
